#!/usr/bin/env node
/*
 * Submits every payload listed in manifest.json against a running instance
 * of this repo's API (which hosts the bundled DIWASS emulator - see
 * CLAUDE.md). Records the ACTUAL response next to the expected one and
 * writes results/validation-results.md as evidence that this payload pack
 * was pre-validated against the emulator, per OR-01's acceptance criteria.
 *
 * Run happy-path and json-level cases through POST /annexvii (the alpha's
 * own JSON API - the same route real DIWASS submissions will go through
 * once DIWASS_BASE_URL points at the real gateway). Run soap-level cases
 * directly against the emulator's /diwass/* routes, since a malformed or
 * conditionally-invalid SOAP body never reaches DIWASS through the JSON
 * layer - the Joi schema would reject it first.
 *
 * Usage: BASE_URL=http://127.0.0.1:3055 node scripts/run-validation.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const BASE_URL = process.env.BASE_URL ?? 'http://127.0.0.1:3055'
const packRoot = new URL('../', import.meta.url)

function packPath(relativePath) {
  return fileURLToPath(new URL(relativePath, packRoot))
}

const manifest = JSON.parse(readFileSync(packPath('manifest.json'), 'utf8'))

const TARGET_PATHS = {
  annexvii: '/annexvii',
  'diwass-annex-vii-raw': '/diwass/annex-vii',
  'diwass-operators-raw': '/diwass/operators'
}

function extractTag(xml, tag) {
  const match = xml.match(new RegExp(`<[\\w:]*${tag}>([^<]*)</[\\w:]*${tag}>`))
  return match ? match[1] : null
}

async function runCase(entry) {
  const filePath = packPath(entry.file)
  const isJson = entry.type === 'json' || entry.target === 'annexvii'
  const body = readFileSync(filePath, 'utf8')
  const path = TARGET_PATHS[entry.target]

  const response = await fetch(`${BASE_URL}${path}`, {
    method: 'POST',
    headers: { 'Content-Type': isJson ? 'application/json' : 'text/xml' },
    body
  })

  const rawText = await response.text()
  const actual = { httpStatus: response.status }

  if (isJson) {
    try {
      const parsed = JSON.parse(rawText)
      actual.diwassStatus = parsed?.diwass?.status
      actual.message = parsed?.message ?? parsed?.diwass?.error
    } catch {
      actual.message = rawText.slice(0, 300)
    }
  } else {
    actual.faultReason = extractTag(rawText, 'faultstring')
    actual.responseSnippet = rawText.replace(/\s+/g, ' ').trim().slice(0, 300)
  }

  return actual
}

function formatExpected(expected) {
  return Object.entries(expected)
    .map(([key, value]) => `${key}=${JSON.stringify(value)}`)
    .join(', ')
}

function formatActual(actual) {
  return Object.entries(actual)
    .filter(([, value]) => value !== undefined)
    .map(([key, value]) => `${key}=${JSON.stringify(value)}`)
    .join(', ')
}

async function main() {
  const rows = []
  const allEntries = [
    ...manifest.happyPath.map((e) => ({ ...e, group: 'Happy path' })),
    ...manifest.errorCases.map((e) => ({ ...e, group: 'Error / edge case' }))
  ]

  for (const entry of allEntries) {
    let actual
    let runError = null
    try {
      actual = await runCase(entry)
    } catch (error) {
      runError = error.message
      actual = {}
    }

    const statusMatches =
      !runError && actual.httpStatus === entry.expected.httpStatus
    rows.push({ entry, actual, runError, statusMatches })

    console.log(
      `[${statusMatches ? 'MATCH' : 'CHECK'}] ${entry.id} - expected httpStatus=${entry.expected.httpStatus}, got ${runError ?? actual.httpStatus}`
    )
  }

  const lines = []
  lines.push('# Annex VII test payload pack - emulator validation results')
  lines.push('')
  lines.push(
    `Generated by \`scripts/run-validation.mjs\` against \`${BASE_URL}\` on ${new Date().toISOString()}.`
  )
  lines.push('')
  lines.push(
    "This is the evidence that every payload in this pack was submitted to a running DIWASS emulator (this repo's own bundled emulator, not real DIWASS) before being marked ready. `statusMatches` compares the HTTP status only - see the `note` column and ASSUMPTIONS.md for anything the emulator accepts today that real DIWASS may not."
  )
  lines.push('')

  let currentGroup = null
  for (const { entry, actual, runError, statusMatches } of rows) {
    if (entry.group !== currentGroup) {
      currentGroup = entry.group
      lines.push(`## ${currentGroup}`)
      lines.push('')
      lines.push('| ID | Payload | Expected | Actual | Status match |')
      lines.push('| --- | --- | --- | --- | --- |')
    }
    const expectedStr = formatExpected(entry.expected)
    const actualStr = runError ? `ERROR: ${runError}` : formatActual(actual)
    lines.push(
      `| ${entry.id} | \`${entry.file}\` | ${expectedStr} | ${actualStr} | ${statusMatches ? 'yes' : 'NO - review'} |`
    )
  }

  lines.push('')
  const outFile = packPath('results/validation-results.md')
  writeFileSync(outFile, lines.join('\n') + '\n')
  console.log(`\nWrote ${outFile}`)

  const mismatches = rows.filter((r) => !r.statusMatches)
  if (mismatches.length > 0) {
    console.log(
      `\n${mismatches.length} case(s) did not match the expected HTTP status - review results/validation-results.md and manifest.json.`
    )
  }
}

main()
